"""Транскрипт и чат для синтетического видео selftest (вместо whisper)."""
import json
import random
import sys
from pathlib import Path

random.seed(1)
SCRIPT = [
    (5.0, "Ребят, есть одно правило. Правило номер четыре, не ставить на Бетбум."),
    (12.0, "Сейчас всё чётенько будет, я вам обещаю."),
    (20.0, "Егор опять БКБ не нажал."),
    (30.0, "Короче, знаете, почему я так играю? Потому что я нормальный, я на контент."),
    (36.5, "На самом деле это пиздец какой-то, честно. Ха-ха-ха."),
    (45.0, "Егор не купил БКБ. Ну может потом купит."),
    (59.0, "Ааа! Что за бред! Ты видел? Рампага!"),
    (70.0, "Быть бум очень плохая команда просто."),
    (80.0, "Егор и БКБ это отдельная история, БКБ не нажал."),
    (90.0, "Правило номер пять, не ставлю против Виспа."),
    (101.0, "Гг, проиграли. Ничего страшного, сейчас две игры выиграем."),
    (112.0, "А вы знаете, как выбрать арбуз? Смотри, надо просто постучать."),
    (117.5, "Если звонкий, значит хороший. Вот это главное правило арбуза."),
    (124.0, "На обидках создал правило, которое меня"),
    (127.2, "и погубило."),
    (135.0, "Браво, Бетбум. Я же говорил."),
]
pdir = Path(sys.argv[1])
segs = []
for t0, text in SCRIPT:
    t, ws = t0, []
    for w in text.split():
        d = 0.12 + 0.045 * len(w)
        ws.append({"start": round(t, 2), "end": round(t + d, 2), "word": w, "p": round(random.uniform(0.3, 1), 2)})
        t += d + 0.06
    segs.append({"start": t0, "end": round(t, 2), "text": text, "words": ws})
(pdir / "transcript.json").write_text(json.dumps({"segments": segs}, ensure_ascii=False, indent=1), encoding="utf-8")
with open(pdir / "chat.jsonl", "w", encoding="utf-8") as f:
    for t in [38, 39, 40, 40.5, 41, 41.2, 42, 43, 66, 67, 68]:
        f.write(json.dumps({"t": t, "text": "ахахах KEKW"}, ensure_ascii=False) + "\n")
    for t in range(0, 150, 7):
        f.write(json.dumps({"t": t, "text": "привет"}, ensure_ascii=False) + "\n")
